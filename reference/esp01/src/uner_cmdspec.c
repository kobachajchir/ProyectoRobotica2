const UNER_CommandSpec *UNER_FindCommandSpec(const UNER_CommandSpec *table, uint8_t count, uint8_t cmd) {
    if (!table) return 0;
    for (uint8_t i = 0; i < count; ++i) if (table[i].id == cmd) return &table[i];
    return 0;
}

