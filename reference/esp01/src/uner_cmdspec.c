const UNER_CommandSpec *UNER_DefaultCommandTable(uint8_t *count) {
    if (count) *count = (uint8_t)(sizeof(g_table) / sizeof(g_table[0]));
    return g_table;
}

UNER_CommandSpec *UNER_MutableCommandTable(uint8_t *count) {
    enum { TABLE_COUNT = (int)(sizeof(g_table) / sizeof(g_table[0])) };
    static UNER_CommandSpec runtime_table[TABLE_COUNT];
    static uint8_t initialized = 0;

    if (!initialized) {
        memcpy(runtime_table, g_table, sizeof(g_table));
        initialized = 1;
    }
    if (count) *count = (uint8_t)TABLE_COUNT;
    return runtime_table;
}
