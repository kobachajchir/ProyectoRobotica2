void Afr2Icon_Draw(Afr2Oled *o,uint8_t id,int16_t x,int16_t y,uint8_t size) {
    if(id>=AFR2_ICON_COUNT || !size)return;
    Icon icon;memcpy_P(&icon,&icons[id],sizeof(icon));
    uint8_t stride=(icon.w+7u)/8u;
    uint8_t largest=icon.w>icon.h?icon.w:icon.h;
    uint8_t width=(uint16_t)icon.w*size/largest,height=(uint16_t)icon.h*size/largest;
    x+=(size-width)/2;y+=(size-height)/2;
    for(uint8_t py=0;py<height;py++)for(uint8_t px=0;px<width;px++) {
        uint8_t sx=(uint16_t)px*icon.w/width,sy=(uint16_t)py*icon.h/height;
        if(pgm_read_byte(icon.bits+(uint16_t)sy*stride+sx/8u)&(1u<<(sx&7u)))Afr2Oled_Pixel(o,x+px,y+py,AFR2_WHITE);
    }
}
uint8_t Afr2Menu_Icon(uint8_t node,uint8_t target,uint8_t action,const char *label) {
    if(!strncmp(label,"Volver",6))return AFR2_ICON_BACK;
    if(action==AFR2_A_REBOOT_MEGA || action==AFR2_A_REBOOT_ESP || target==AFR2_N_REBOOT)return AFR2_ICON_REFRESH;
    if(target==AFR2_N_AP_INFO || node==AFR2_N_WIFI_AP)return AFR2_ICON_AP;
    if(target==AFR2_N_WIFI || target==AFR2_N_NETWORK || node==AFR2_N_WIFI || (action>=AFR2_A_WIFI_STATUS && action<=AFR2_A_WIFI_SET_MODE))return AFR2_ICON_WIFI;
    if(target==AFR2_N_ENCODER_VIEW || target==AFR2_N_ENCODER_CONFIG)return AFR2_ICON_ENCODER;
    if(target==AFR2_N_SENSORS || target==AFR2_N_LINE_VIEW || target==AFR2_N_US_VIEW || target==AFR2_N_HALL_VIEW)return AFR2_ICON_SENSORS;
    if(target==AFR2_N_PREFS || target==AFR2_N_PREFS_VIEW || action==AFR2_A_SAVE || action==AFR2_A_DISCARD)return AFR2_ICON_PREFS;
    if(target==AFR2_N_LINK_VIEW)return AFR2_ICON_LINK;
    if(target==AFR2_N_CONTROL || target==AFR2_N_MOVE || target==AFR2_N_WHEEL || node==AFR2_N_MOVE || node==AFR2_N_WHEEL)return AFR2_ICON_MOTOR;
    if(target==AFR2_N_TESTS || target==AFR2_N_CALIB || node==AFR2_N_TESTS || node==AFR2_N_CALIB)return AFR2_ICON_TOOLS;
    if(target==AFR2_N_SYSTEM || target==AFR2_N_DISPLAY_MENU || node==AFR2_N_SYSTEM || node==AFR2_N_DISPLAY_MENU)return AFR2_ICON_CONFIG;
    if(action==AFR2_A_STOP || target==AFR2_N_ALERT_VIEW)return AFR2_ICON_WARNING;
    return AFR2_ICON_INFO;
}
